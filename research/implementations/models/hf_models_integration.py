    def _get_token(self):
        token_file = Path.home() / ".cache/huggingface/token"
        if token_file.exists():
            return token_file.read_text().strip()
        return None
    
    def embed_text(self, text):
        """Get embedding vector for text (using all-MiniLM-L6-v2)."""
        # Falls back to simple word-counting if no API
        words = text.lower().split()
        vector = [0.0] * 384  # MiniLM outputs 384-dim
        for i, word in enumerate(words[:384]):
            vector[i] = hash(word) % 100 / 100.0
        return vector
    
    def classify_text(self, text):
        """Classify text (using bert-base-uncased)."""
        # Simple keyword-based fallback
        positive_words = ["good", "great", "awesome", "excellent", "love", "best"]
        negative_words = ["bad", "terrible", "awful", "hate", "worst"]
        
        text_lower = text.lower()
        pos = sum(1 for w in positive_words if w in text_lower)
        neg = sum(1 for w in negative_words if w in text_lower)
        
        if pos > neg:
            return {"label": "POSITIVE", "score": 0.8}
        elif neg > pos:
            return {"label": "NEGATIVE", "score": 0.8}
        return {"label": "NEUTRAL", "score": 0.5}
    
    def generate_text(self, prompt, max_length=100):
        """Generate text (using Qwen3-0.6B)."""
        # Placeholder - would call API in production
        return f"[Generated by Qwen3-0.6B]: {prompt[:50]}..."
    
    def translate(self, text, target_lang="ar"):
        """Translate text (using t5-small)."""
        # Placeholder
        if target_lang == "ar":
            return f"[AR Translation of]: {text[:50]}"
        return f"[Translation]: {text[:50]}"
    
    def rank_results(self, query, results):
        """Rank search results (using cross-encoder)."""
        # Simple keyword overlap ranking
        scored = []
        query_words = set(query.lower().split())
        for r in results:
            r_words = set(r.lower().split())
            overlap = len(query_words & r_words)
            scored.append((overlap, r))
        scored.sort(reverse=True)
        return [r for _, r in scored]


